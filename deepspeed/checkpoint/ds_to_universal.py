def _get_optim_files(checkpoint_dir):
    # The MoE save path also writes expp_rank_<n>_mp_rank_<m>_optim_states.pt placeholders
    # ({'optimizer': None}), which match "*_optim_states.pt" but are not ZeRO shards. Sorted
    # naturally, 'expp_rank_0...' precedes 'fp16_zero_pp_rank_0...', so _get_zero_stage would
    # read one of the placeholders and raise KeyError: 'optimizer_state_dict'. reshape_utils
    # already knows the three real ZeRO prefixes; ask it.
    files = get_zero_files(checkpoint_dir)
    if not files:
        # Most common cause by far: a weights-only folder. Say so, rather than making the user
        # guess which of the three prefixes was expected.
        raise FileNotFoundError(
            f"no ZeRO optimizer files (zero_pp_rank_* / bf16_zero_pp_rank_* / fp16_zero_pp_rank_*) "
            f"in '{checkpoint_dir}'. Universal checkpointing converts optimizer state, so a "
            f"weights-only checkpoint (e.g. one produced by an HF import tool) is not a valid input.")
    return files


def _get_model_state_files(checkpoint_dir):
    return _get_checkpoint_files(checkpoint_dir, "*_model_states.pt")


def _get_checkpoint_files(checkpoint_dir, glob_pattern):
    ckpt_files = sorted(glob.glob(os.path.join(checkpoint_dir, glob_pattern)), key=natural_keys)

    if len(ckpt_files) == 0:
        raise FileNotFoundError(f"can't find {glob_pattern} files in directory '{checkpoint_dir}'")

    return ckpt_files


def _get_zero_stage(optim_files):
    state_dict = load_checkpoint_file(optim_files[0])
    optimizer_state = state_dict[OPTIMIZER_STATE_DICT]
    zero_stage = optimizer_state.get(ZERO_STAGE, 1)
    return zero_stage


def _inject_missing_state(ds_checkpoint):
    if UNIVERSAL_CHECKPOINT_INFO not in ds_checkpoint.global_state:
        sd = load_checkpoint_file(ds_checkpoint.mp_rank_files[0])
        if UNIVERSAL_CHECKPOINT_INFO not in sd:
            ds_checkpoint.global_state[UNIVERSAL_CHECKPOINT_INFO] = {}
            ds_checkpoint.global_state[UNIVERSAL_CHECKPOINT_INFO][
                UNIVERSAL_CHECKPOINT_VERSION_KEY] = UNIVERSAL_CHECKPOINT_VERSION_VALUE


def _check_for_required_state(ds_checkpoint):
    universal_checkpoint_info = ds_checkpoint.get_checkpoint_info(UNIVERSAL_CHECKPOINT_INFO)
    assert universal_checkpoint_info is not None, f'Required {UNIVERSAL_CHECKPOINT_INFO} state is missing in checkpoint. Verify that client creates this state.'


def main(args):
    print(f'Convert DeepSpeed Checkpoint to Universal Checkpoint')

    print(f'Converting DeepSpeed checkpoint in {args.input_folder} to Universal checkpoint in {args.output_folder}')

    optim_files = _get_optim_files(args.input_folder)
    zero_stage = _get_zero_stage(optim_files)

    if zero_stage <= 2:
        ds_checkpoint = DeepSpeedCheckpoint(args.input_folder)
        if args.inject_missing_state:
            _inject_missing_state(ds_checkpoint)
        else:
            _check_for_required_state(ds_checkpoint)

        iteration = ds_checkpoint.get_iteration()
        #_create_latest_file(args.output_folder, iteration)
        checkpoint_paths = _create_checkpoint_paths(args.output_folder, iteration, ds_checkpoint.tp_degree,
                                                    ds_checkpoint.pp_degree)

        slice_shapes = []
        for mp_rank_file in ds_checkpoint.mp_rank_files:
            mp_sd = load_checkpoint_file(mp_rank_file)
            if PARAM_SHAPES not in mp_sd or mp_sd[PARAM_SHAPES] is None:
                raise KeyError(
                    f"'{PARAM_SHAPES}' is missing from {os.path.basename(mp_rank_file)}. It records "
                    f"which parameters the optimizer's flat buffers hold, and cannot be "
                    f"reconstructed after the fact. Re-save the checkpoint with a build that "
                    f"records it.")
            slice_shapes += mp_sd[PARAM_SHAPES]

        # Flatten, merging duplicates for tp>1. For MoE this also materialises every global
        # expert: param_shapes is written by one rank and names only its local experts, so
        # without this the merge phase would skip all but one expert-parallel rank's share.
        # If experts are present but their metadata is not, the number of experts cannot be
        # known and expand_moe_param_shapes would silently emit one expert-parallel rank's
        # share. That converts without error and dies on the first missing atom at resume, so
        # refuse here where the cause is still visible.
        moe_info = ds_checkpoint._get_checkpoint_value(MOE_UCP_INFO)
        flat_names = {name for group in slice_shapes for name in group}
        if moe_info is None and any(is_expert_param_name(name) for name in flat_names):
            raise RuntimeError(
                f"this checkpoint has expert-parallel parameters but no '{MOE_UCP_INFO}' "
                f"record in any of its {len(ds_checkpoint.mp_rank_files)} model-state files, "
                f"so the total number of experts cannot be determined. It was written by a "
                f"build that predates the record; re-save it with a current build.")

        # An expert implementation that stacks all of a rank's experts into one tensor leaves
        # those parameters with expert-parallel-rank-local names. Every rank then writes the
        # same name, so the atoms silently overwrite each other and the converted checkpoint
        # holds one rank's experts presented as all of them. The engine cannot refuse at save
        # time without killing training that never intended to convert, so it records the fact
        # and the refusal lands here, where the user is asking for the conversion.
        if moe_info is not None and not moe_info.get('expert_names_globalized', True):
            raise RuntimeError(
                "this checkpoint's expert parameters have expert-parallel-rank-local names, so "
                "each expert-parallel rank's optimizer state would be written to the same "
                "place and all but one rank's experts would be lost. The expert module used "
                "stacks its local experts into shared tensors, which have no per-expert name "
                "to make globally unique. Universal checkpointing does not support that expert "
                "implementation; re-train with the unfused Experts module to convert.")

        slice_shapes = expand_moe_param_shapes(slice_shapes, moe_info)
        if moe_info:
            n_expert = sum(1 for k in slice_shapes if is_expert_param_name(k))
            print(f'*** MoE checkpoint: {n_expert} expert parameters across '
                  f"{moe_info.get('ep_size')} expert-parallel ranks")
        temp_dir = os.path.join(args.output_folder, 'tmp')

        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('startup', _TIMING_T0_NS, _TIMING_T0_ABS)
        print('*** 1. Extracting ZeRO fragments')
        _extract_zero_shard_files(args, ds_checkpoint, temp_dir)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('extract', t_ph, t_ph_abs)

        print('*** 2. Merging slices .....')
        _merge_tp_slice_files(args, ds_checkpoint, slice_shapes, temp_dir)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('merge', t_ph, t_ph_abs)

        print('*** 3. Saving common optimizer states')
        _save_optimizer_state(args, ds_checkpoint)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('optstate', t_ph, t_ph_abs)

        if not args.keep_temp_folder:
            shutil.rmtree(temp_dir, ignore_errors=True)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('cleanup', t_ph, t_ph_abs)

        # Copy mp* files into output folder
        for f in glob.glob(os.path.join(args.input_folder, 'mp*')):
            shutil.copy2(f, args.output_folder)
        if _TIMING:
            _timing_phase_end('copy_mp', t_ph, t_ph_abs)

    else:
        model_files = _get_model_state_files(args.input_folder)
        param_shapes = _parse_model_states_stage3(model_files)
        param_shapes = {k: v for d in param_shapes for k, v in d.items()}
        dp_degree = len(model_files)

        temp_dir = os.path.join(args.output_folder, 'tmp')

        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('startup', _TIMING_T0_NS, _TIMING_T0_ABS)
        print('*** 1. Extracting ZeRO fragments')
        _extract_zero_shard_files_stage3(args, optim_files, param_shapes, dp_degree, temp_dir)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('extract', t_ph, t_ph_abs)

        print('*** 2. Merging slices .....')
        _merge_zero3_slice_files(args, param_shapes, dp_degree, temp_dir)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('merge', t_ph, t_ph_abs)

        print('*** 3. Saving common optimizer states')
        _save_optimizer_state_stage3(args, optim_files)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('optstate', t_ph, t_ph_abs)

        if not args.keep_temp_folder:
            shutil.rmtree(temp_dir, ignore_errors=True)
        if _TIMING:
            t_ph, t_ph_abs = _timing_phase_end('cleanup', t_ph, t_ph_abs)

        # Copy *model_states files into output folder
        for f in glob.glob(os.path.join(args.input_folder, '*model_states.pt')):
            shutil.copy2(f, args.output_folder)
        if _TIMING:
            _timing_phase_end('copy_mp', t_ph, t_ph_abs)

    # Update latest to output folder
    checkpoint_root_folder, step_folder = os.path.split(args.output_folder)
    latest_file = os.path.join(checkpoint_root_folder, 'latest_universal')
    with open(latest_file, "w") as f:
        f.write(step_folder)

    if _TIMING:
        _timing_phases_report(args)
    print('*** Done!')


if __name__ == "__main__":
    args = parse_arguments()
    main(args)
