def extract_zero_shards(dir, ds_checkpoint, indices_3D):
    pp_index, tp_index, dp_index = indices_3D
    t_task0 = time.perf_counter_ns() if _TIMING else 0
    sd = ds_checkpoint.get_zero_checkpoint_state(pp_index=pp_index, tp_index=tp_index, dp_index=dp_index)
    if _TIMING:
        _timing_shard_load(ds_checkpoint, indices_3D, t_task0, time.perf_counter_ns())
        cnt0 = cnt

    # pprint(f"Processing {dp_index=} {pp_index=}, {tp_index=}")

    optim_sd = sd[OPTIMIZER_STATE_DICT]
    param_slice_mappings = optim_sd[PARAM_SLICE_MAPPINGS]
    # Experts are replicated across tensor-parallel ranks unless the model was built with
    # expert tensor parallelism; see out_tp below.
    experts_are_replicated = not (ds_checkpoint._get_checkpoint_value(MOE_UCP_INFO) or {}).get(
        'expert_tensor_parallel', False)

    # Expert parameter names are made globally unique by the engine, before ZeRO records them
    # (deepspeed/moe/utils.py globalize_expert_param_names). A checkpoint from a build that
    # instead renamed them here carries a per-rank 'moe_ucp_rank' record and rank-local names;
    # converting it now would write every expert-parallel rank into the same atom directory
    # and report success. There is no way to tell the two apart from the names alone, so key
    # on the record that only the older format has.
    if 'moe_ucp_rank' in optim_sd:
        raise RuntimeError(
            'this checkpoint was written by a build that named expert parameters rank-locally '
            'and renamed them during conversion. That record is no longer produced or read; '
            'expert names are now global in the checkpoint itself. Re-save the checkpoint with '
            'a current build before converting it.')

    universal_checkpoint_info = ds_checkpoint.get_checkpoint_info(UNIVERSAL_CHECKPOINT_INFO)
    pipeline_replicated_params = universal_checkpoint_info.get(PIPELINE_REPLICATED_PARAMETER_PATTERNS, [])
    # print(f'{pipeline_replicated_params=}')

    # dict
    state_groups = optim_sd[BASE_OPTIMIZER_STATE]["state"]
    # list
    fp32_groups = optim_sd[SINGLE_PARTITION_OF_FP32_GROUPS]
    param_groups_cnt = len(state_groups)

    for param_group_id in range(param_groups_cnt):

        flat_state = dict(
            exp_avg=state_groups[param_group_id]["exp_avg"],
            exp_avg_sq=state_groups[param_group_id]["exp_avg_sq"],
            fp32=fp32_groups[param_group_id],
        )

        if "step" in state_groups[param_group_id]:
            flat_state["step"] = state_groups[param_group_id]["step"]

        for name, fragment_mapping in param_slice_mappings[param_group_id].items():
            if pp_index > 0 and any(re.match(pattern, name) for pattern in pipeline_replicated_params):
                # Skip tied weights that are replicated in first and last pp stages
                continue

            # A fragment's directory is keyed by (tp_index, dp_index). For an expert that
            # tensor parallelism does not shard, tp_index says nothing about the tensor, and
            # keying on it splits one expert's fragments across tp_degree directories: the
            # expert-parallel groups are carved from the global rank space with no reference
            # to TP (deepspeed/utils/groups.py), so two ranks holding different fragments of
            # the same expert share an expert-parallel position but need not share a
            # tp_rank. _merge_zero_shards would then find only a subset and the reshape
            # would fail. Collapse them onto tp_index 0; each (expert, dp_index) is still
            # written exactly once, because the expert groups partition the world.
            out_tp = 0 if (experts_are_replicated and is_expert_param_name(name)) else tp_index
            for state_key in flat_state.keys():
                dump_param_fragment(dir, out_tp, dp_index, state_key, flat_state[state_key], name,
                                    fragment_mapping.start, fragment_mapping.numel)
    if _TIMING:
        _timing_record('extract_task', f'pp{pp_index}_tp{tp_index}_dp{dp_index}', '', tp_index, dp_index, dir, '',
                       t_task0, time.perf_counter_ns(), f'mode=file;n_frag={cnt - cnt0}')


def extract_zero_shards_stage3(optim_files, param_shapes, dp_degree, temp_dir, dp_index):
    state_dict = load_checkpoint_file(optim_files[dp_index])

    flat_state = dict(
        exp_avg=state_dict[OPTIMIZER_STATE_DICT]['optimizer_state_dict']['state'][0]["exp_avg"],
        exp_avg_sq=state_dict[OPTIMIZER_STATE_DICT]['optimizer_state_dict']['state'][0]["exp_avg_sq"],
        fp32=state_dict[OPTIMIZER_STATE_DICT]['fp32_flat_groups'][0],
    )

    offset = 0
    for name, shape in param_shapes.items():
        unpartitioned_numel = shape.numel()
        partitioned_numel, _ = _zero_partitioned_param_info(unpartitioned_numel, dp_degree)
        padding_free_numel = min(partitioned_numel, abs(unpartitioned_numel - dp_index * partitioned_numel))
        for state_key in flat_state.keys():
            dump_param_fragment(temp_dir, 0, dp_index, state_key, flat_state[state_key], name, offset,
                                padding_free_numel)
        offset += partitioned_numel


cnt = 0


def dp_index_to_str(dp_index):
    return f"{dp_index:0>2d}"


def dump_param_fragment(dir, tp_index, dp_index, state_name, state_flat_tensor, param_name, offset, numel):

    global cnt  # temp hack

    param_base_path = os.path.join(dir, param_name, str(tp_index))
    os.makedirs(param_base_path, exist_ok=True)

    cnt += 1

    path = os.path.join(param_base_path, f"{state_name}.{dp_index_to_str(dp_index)}")

    #print(f"{param_name}: {offset}: {numel} => {path}")

    # State might be a python int or a tensor
    t0 = time.perf_counter_ns() if _TIMING else 0
    if state_name != "step" and torch.is_tensor(state_flat_tensor):
        state_flat_tensor = state_flat_tensor.narrow(0, offset, numel).clone()
    t1 = time.perf_counter_ns() if _TIMING else 0
    _save_checkpoint(path, state_flat_tensor)
    if _TIMING:
        _timing_record('frag_write', param_name, state_name, tp_index, dp_index, path, _timing_nbytes(state_flat_tensor),
                       t1, time.perf_counter_ns(), f'clone_ns={t1 - t0}')


def _merge_zero_shards(param_base_path, state, tp_degree, slice_shape=None):
    slices = []
    for tp_index in range(tp_degree):
        prefix_path = os.path.join(param_base_path, str(tp_index), f"{state}")
        paths = glob.glob(f"{prefix_path}.*")

        if len(paths) == 0:
            continue

        pattern = re.compile(f"{prefix_path}\\.([0-9]+)")
        dp_indices = set()
        for p in paths:
            m = pattern.match(p)
            if m:
                dp_indices.add(int(m.group(1)))
            else:
                raise ValueError(f"Cannot parse dp_rank from {p}")

        paths = [f"{prefix_path}.{dp_index_to_str(dp_index)}" for dp_index in sorted(list(dp_indices))]
        if _TIMING:
            shards = [
                _timing_frag_read(p, os.path.basename(param_base_path), state, tp_index, dp)
                for dp, p in zip(sorted(dp_indices), paths)
            ]
        else:
            shards = [load_checkpoint_file(p) for p in paths]

        if state == "step":
            assert all(v == shards[0] for v in shards), "All shards must have the same step value"
            slice = shards[0]
        else:
            if slice_shape is None:
                slice = torch.cat(shards, dim=0)
            else:
                slice = torch.cat(shards, dim=0).reshape(slice_shape)

        slices.append(slice)
    return slices


